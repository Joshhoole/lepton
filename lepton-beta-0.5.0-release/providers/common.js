// Helpers shared by every provider module.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const UPLOADS = path.join(ROOT, 'uploads');
fs.mkdirSync(UPLOADS, { recursive: true });

const MIME = {
  '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.gif': 'image/gif',
  '.mp4': 'video/mp4', '.mov': 'video/quicktime', '.webm': 'video/webm',
  '.mp3': 'audio/mpeg', '.wav': 'audio/wav', '.m4a': 'audio/mp4', '.ogg': 'audio/ogg', '.aac': 'audio/aac', '.flac': 'audio/flac',
};
const EXT_FOR = { 'image/png': '.png', 'image/jpeg': '.jpg', 'image/webp': '.webp', 'image/gif': '.gif', 'video/mp4': '.mp4', 'video/quicktime': '.mov', 'video/webm': '.webm', 'audio/mpeg': '.mp3', 'audio/wav': '.wav', 'audio/mp4': '.m4a', 'audio/ogg': '.ogg' };
const mimeOf = (p) => MIME[path.extname(p).toLowerCase()] || 'application/octet-stream';
const kindOf = (mime) => (mime.startsWith('video/') ? 'video' : mime.startsWith('audio/') ? 'audio' : 'image');

class ApiError extends Error {
  constructor(message, { code = 'API_ERROR', status } = {}) { super(message); this.code = code; this.status = status; }
}

// fetch() with timeout + JSON handling. Throws ApiError with a readable message on non-2xx.
async function fetchJson(url, { method = 'GET', headers = {}, body, timeoutMs = 60000, raw = false, form } = {}) {
  const ctrl = new AbortController();
  const t = setTimeout(() => ctrl.abort(), timeoutMs);
  let r;
  try {
    r = await fetch(url, {
      method, signal: ctrl.signal,
      headers: form ? headers : { 'Content-Type': 'application/json', Accept: 'application/json', ...headers },
      body: form ? form : body === undefined ? undefined : typeof body === 'string' ? body : JSON.stringify(body),
    });
  } catch (e) {
    clearTimeout(t);
    throw new ApiError(e.name === 'AbortError' ? 'The request timed out' : `Network error: ${e.message}`, { code: 'NETWORK' });
  }
  clearTimeout(t);
  if (raw) {
    if (!r.ok) throw new ApiError(await describeError(r), { code: authCode(r.status), status: r.status });
    return r;
  }
  const text = await r.text();
  let data = null;
  try { data = text ? JSON.parse(text) : null; } catch { data = text; }
  if (!r.ok) throw new ApiError(errorMessage(r.status, data), { code: authCode(r.status), status: r.status });
  return data;
}
async function describeError(r) { let d = null; try { d = JSON.parse(await r.text()); } catch { /* ignore */ } return errorMessage(r.status, d); }
const authCode = (s) => (s === 401 || s === 403 ? 'API_AUTH' : s === 402 ? 'API_CREDITS' : s === 404 ? 'API_404' : s === 429 ? 'RATE_LIMIT' : 'API_ERROR');
function errorMessage(status, data) {
  if (data && typeof data === 'object') {
    const d = data.detail ?? data.error ?? data.message;
    // Google free-tier quota: the model simply isn't available without billing.
    if (d && typeof d === 'object' && /free_tier/.test(JSON.stringify(d)) && /limit: 0/.test(JSON.stringify(d))) {
      const model = (JSON.stringify(d).match(/model: ([\w.\-]+)/) || [])[1];
      return `Google: ${model || 'this model'} has no free-tier quota. Enable billing on the Google Cloud project behind your API key (AI Studio → your project → Billing), then try again.`;
    }
    if (d && typeof d === 'object' && /RESOURCE_EXHAUSTED|quota/i.test(JSON.stringify(d))) return `Google: quota exceeded. ${(d.message || '').split('\n')[0]}`;
    if (typeof d === 'string') return d;
    if (Array.isArray(d)) return d.map((x) => (x.loc ? `${x.loc.filter((l) => l !== 'body').join('.')}: ${x.msg}` : x.msg || x.message || JSON.stringify(x))).join('; ');
    if (d && typeof d === 'object') return d.message || d.detail || JSON.stringify(d);
  }
  if (status === 401 || status === 403) return 'The API rejected this key.';
  if (status === 402) return 'Not enough credits or billing not set up on this account.';
  if (status === 429) return 'Rate limited. Try again in a moment.';
  return `API error (HTTP ${status})`;
}

// Persist generated bytes locally and return the URL the page can load.
function saveResult(buf, mime, prefix = 'gen') {
  const ext = EXT_FOR[mime] || '.bin';
  const name = `${prefix}-${crypto.randomBytes(6).toString('hex')}${ext}`;
  fs.writeFileSync(path.join(UPLOADS, name), buf);
  return `/uploads/${name}`;
}

// Media saved into a project folder is addressed as /projects/<id>/media/<file>; the server registers how to find it.
let projectMedia = null;
function setProjectMediaResolver(fn) { projectMedia = fn; }

// Turn a media reference from the page into a local file. Accepts /uploads/… paths, project media paths and https URLs
// (downloaded once and cached).
async function localFile(m, downloadHeaders = {}) {
  const ref = String((m && (m.ref || m.url)) || '');
  const inProject = ref.startsWith('/projects/') ? ref : m && m.url && String(m.url).startsWith('/projects/') ? m.url : null;
  if (inProject) {
    const abs = projectMedia ? projectMedia(inProject) : null;
    if (!abs) throw new ApiError(`This file is missing from its project folder: ${decodeURIComponent(inProject.split('/').slice(4).join('/')) || inProject}. Drop it onto the board again.`);
    return { abs, mime: mimeOf(abs), url: null };
  }
  const url = m && m.url && /^https?:\/\//.test(m.url) ? m.url : /^https?:\/\//.test(ref) ? ref : null;
  const local = ref.startsWith('/uploads/') ? ref : m && m.url && String(m.url).startsWith('/uploads/') ? m.url : null;
  if (local) {
    const abs = path.join(UPLOADS, path.basename(local));
    if (!abs.startsWith(UPLOADS) || !fs.existsSync(abs)) throw new ApiError(`Upload missing on disk: ${local}`);
    return { abs, mime: mimeOf(abs), url: null };
  }
  if (url) {
    const name = `remote-${crypto.createHash('sha1').update(url).digest('hex').slice(0, 12)}${path.extname(new URL(url).pathname) || ''}`;
    let abs = path.join(UPLOADS, name);
    if (!fs.existsSync(abs)) {
      const r = await fetchJson(url, { raw: true, headers: downloadHeaders, timeoutMs: 120000 });
      const buf = Buffer.from(await r.arrayBuffer());
      const ct = (r.headers.get('content-type') || '').split(';')[0];
      if (!path.extname(abs) && EXT_FOR[ct]) abs += EXT_FOR[ct];
      fs.writeFileSync(abs, buf);
    }
    return { abs, mime: mimeOf(abs), url };
  }
  throw new ApiError('This input has no file. Re-run the upstream node or upload the media.');
}
const b64 = (abs) => fs.readFileSync(abs).toString('base64');

// Standard parameter helper for provider catalogues.
const P = (name, type, def, en, extra = {}) => ({ name, type, default: def, enum: en, required: false, ...extra });

module.exports = { ROOT, UPLOADS, MIME, EXT_FOR, mimeOf, kindOf, ApiError, fetchJson, saveResult, localFile, setProjectMediaResolver, b64, P };
